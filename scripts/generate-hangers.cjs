'use strict';
// Writes the shared hanger catalog for both platforms from windows/lib/hangers.cjs.
const fs=require('node:fs'),path=require('node:path');
const {HANGERS,ROPE_Y,BOX,hangerFor}=require('../windows/lib/hangers.cjs');
const samples=['3F2504E0-4F89-11D3-9A0C-0305E82C3301','00000000-0000-4000-8000-000000000001','C0FFEE00-1234-4ABC-8DEF-0123456789AB'].map(id=>({id,...hangerFor(id)}));
const root=path.join(__dirname,'..');
fs.writeFileSync(path.join(root,'contracts/hangers.json'),JSON.stringify({version:1,box:BOX,ropeY:ROPE_Y,size:[0.82,1.22],leanDegrees:7,samples,hangers:HANGERS},null,1)+'\n');
const swift=['// Generated by scripts/generate-hangers.cjs from windows/lib/hangers.cjs. Do not edit.','','enum HangerCatalog {','    static let svgs: [String] = ['];
for(const h of HANGERS)swift.push('        '+JSON.stringify(h.svg)+',');
swift.push('    ]','    static let names: [String] = [');
for(const h of HANGERS)swift.push('        '+JSON.stringify(h.name)+',');
swift.push('    ]','}','');
fs.writeFileSync(path.join(root,'Sources/Tendedero/HangerCatalog.swift'),swift.join('\n'));
console.log(HANGERS.length+' hangers written');
