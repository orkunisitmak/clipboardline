'use strict';
const crypto=require('node:crypto');

// Exclusion markers apply to the entire native copy, including markers carried
// by a different item or wrapped in Electron's raw-format MIME type.
function privateClipboard(formats){
  return formats.some(format=>/concealed|transienttype|autogeneratedtype|password|agilebits|ExcludeClipboardContentFromMonitorProcessing|ClipBoardLine\.Internal\.v1/i.test(format));
}
function validSequence(value){return Number.isInteger(value)&&value>0&&value<=0xffffffff;}
const changed=Object.freeze({raced:true});
// Only a single valid URL can replace a copied display label. Reject
// ambiguous multi-link copies rather than silently saving the wrong target.
function oneURL(urls,plainURL){
  const values=[...new Set(urls.map(plainURL).filter(Boolean))];
  return values.length===1?values[0]:null;
}
function linkedURL(format,value,plainURL){
  if(format==='text/uri-list'){
    const lines=value.split(/\r?\n/).map(line=>line.trim()).filter(line=>line&&!line.startsWith('#'));
    return lines.length===1?plainURL(lines[0]):null;
  }
  // This parses URL attributes only, not HTML content or scripts. Invalid
  // schemes, credentials and malformed inputs are rejected by plainURL.
  const attrs=[...value.matchAll(/<a\b[^>]*?\bhref\s*=\s*(?:"([^"]*)"|'([^']*)'|([^\s>]+))/gi)];
  if(attrs.length!==1)return null;
  const href=(attrs[0][1]??attrs[0][2]??attrs[0][3])
    .replace(/&(?:amp|#38|#x26);/gi,'&');
  return oneURL([href],plainURL);
}
async function linkedClipboardRepresentation(entries,plainURL){
  for(const format of ['text/uri-list','text/html']){
    const entry=entries.find(item=>item.types.includes(format));
    if(!entry)continue;
    let blob;
    try{blob=await entry.getType(format);}catch{continue;}
    if(!blob||blob.size>1024*1024)continue;
    let value;
    try{value=new TextDecoder('utf-8',{fatal:true,ignoreBOM:true}).decode(await blob.arrayBuffer());}catch{continue;}
    if(value.length>1024*1024)continue;
    const url=linkedURL(format,value,plainURL);
    if(url)return url;
  }
  return null;
}

// With link capture off a standalone URL is ordinary text, as on macOS.
async function readClipboardContent({clipboard,sequence,marker,plainURL,captureLinks=true}){
  let before;try{before=await sequence();}catch{return null;}if(!validSequence(before))return null;
  const current=async()=>{try{return await sequence()===before;}catch{return false;}};
  const entries=await clipboard.read();
  if(!Array.isArray(entries)||privateClipboard(entries.flatMap(item=>item.types)))return null;
  if(!await current())return changed;
  let owned=false;
  for(const entry of entries){for(const format of entry.types){
    if(format==='web application/x.clipboardline'){
      const blob=await entry.getType(format);if(blob.size!==marker.length)return null;
      const bytes=Buffer.from(await blob.arrayBuffer());owned ||= bytes.equals(marker);
    }
    if(format.includes('CanIncludeInClipboardHistory')){
      const blob=await entry.getType(format);if(blob.size!==4)return null;
      const bytes=Buffer.from(await blob.arrayBuffer());if(bytes.readUInt32LE(0)===0)return null;
    }
  }}
  if(owned)return null;
  if(!await current())return changed;
  const image=entries.find(item=>item.types.includes('image/png'));
  let kind,value,bytes;
  if(image){
    const blob=await image.getType('image/png');if(blob.size>64*1024*1024)return null;
    bytes=Buffer.from(await blob.arrayBuffer());kind='image';value=bytes;
  }else{
    // Electron exposes a linked copy's destination separately from its display
    // label. Prefer that native bookmark only when the user enabled link capture.
    if(captureLinks){
      const bookmark=entries.find(item=>item.types.includes('electron application/bookmark'));
      if(bookmark)try{
        const payload=await bookmark.getType('electron application/bookmark');
        const url=plainURL(payload?.url);
        if(url){bytes=Buffer.from(url,'utf8');kind='link';value=url;}
      }catch{}
    }
    if(kind!=='link'&&captureLinks){
      const url=await linkedClipboardRepresentation(entries,plainURL);
      if(url){bytes=Buffer.from(url,'utf8');kind='link';value=url;}
    }
    if(kind!=='link'){
      // Use this item's payload, never a second live readText() of a replacement
      // clipboard whose private formats have not been inspected.
      const text=entries.find(item=>item.types.includes('text/plain'));if(!text)return null;
      const blob=await text.getType('text/plain');if(blob.size>1024*1024)return null;
      bytes=Buffer.from(await blob.arrayBuffer());if(bytes.length>1024*1024)return null;
      try{value=new TextDecoder('utf-8',{fatal:true,ignoreBOM:true}).decode(bytes);}catch{return null;}
      if(!value||! /\P{White_Space}/u.test(value))return null;
      const url=captureLinks?plainURL(value):null;kind=url?'link':'text';if(url)value=url;
    }
  }
  if(!await current())return changed;
  return{kind,value,sequence:before,owned:false,fingerprint:kind+':'+crypto.createHash('sha256').update(bytes).digest('hex')};
}
// A notification is a repeat only for the same native generation. An identical later copy is a new copy
// (it re-adds an item the user deleted or hid), as macOS changeCount does.
function repeatedGeneration(state,content){if(content.sequence===state.sequence)return true;state.sequence=content.sequence;return false;}
module.exports={privateClipboard,readClipboardContent,repeatedGeneration};
